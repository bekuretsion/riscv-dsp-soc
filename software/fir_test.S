.section .text
.globl _start

_start:

    # FIR base address
    # x10 = 0x40000000
    lui x10, 0x40000


    # --------------------------------
    # Coefficient 0 = 1
    # --------------------------------
    addi x5, x0, 1
    sw   x5, 4(x10)


    # --------------------------------
    # Coefficient 1 = 2
    # --------------------------------
    addi x5, x0, 2
    sw   x5, 8(x10)


    # --------------------------------
    # Coefficient 2 = 3
    # --------------------------------
    addi x5, x0, 3
    sw   x5, 12(x10)


    # --------------------------------
    # Coefficient 3 = 4
    # --------------------------------
    addi x5, x0, 4
    sw   x5, 16(x10)


    # --------------------------------
    # Input sample = 10
    # --------------------------------
    addi x5, x0, 10
    sw   x5, 0(x10)


    # --------------------------------
    # Start FIR
    # CONTROL = 1
    # --------------------------------
    addi x5, x0, 1
    sw   x5, 20(x10)


    # --------------------------------
    # Read FIR result
    #
    # Expected x9 = 10
    # --------------------------------
    lw   x9, 24(x10)


done:
    j done